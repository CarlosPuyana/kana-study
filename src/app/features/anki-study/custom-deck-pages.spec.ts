import { signal } from '@angular/core';
import { TestBed } from '@angular/core/testing';
import { ActivatedRoute, convertToParamMap, provideRouter } from '@angular/router';
import { IDBFactory, IDBKeyRange } from 'fake-indexeddb';
import { AnkiCardsPage } from '../anki-cards/anki-cards.page';
import { AnkiStudyPage } from './anki-study.page';
import { AnkiSettingsPage } from '../anki-settings/anki-settings.page';
import { AnkiStatsPage } from '../anki-stats/anki-stats.page';
import { CustomDeckRepository, CUSTOM_DECKS_ENABLED, CUSTOM_DECK_IDB } from '../../core/services/custom-deck.repository';
import { WorkspaceService } from '../../core/services/workspace.service';
import { TranslationService } from '../../core/services/translation.service';
import {lexicalIdentity} from '../../core/services/custom-deck-validation';
import { customDeck, customCard } from '../../core/services/custom-deck.fixture';
describe('Custom deck deep links use their actual content and the shared study UI', () => {
    beforeEach(async () => { TestBed.resetTestingModule(); localStorage.clear(); const factory = new IDBFactory(); vi.stubGlobal('indexedDB', factory); vi.stubGlobal('IDBKeyRange', IDBKeyRange); await TestBed.configureTestingModule({ providers: [provideRouter([]), { provide: CUSTOM_DECK_IDB, useValue: factory }, { provide: CUSTOM_DECKS_ENABLED, useValue: signal(true) }, { provide: ActivatedRoute, useValue: { snapshot: { paramMap: convertToParamMap({ deckId: 'md-試験' }) } } }, { provide: TranslationService, useValue: { language: signal('ca'), t: (key: string) => key } }] }).compileComponents(); await TestBed.inject(CustomDeckRepository).create('fixture', customDeck(), [await customCard()]); });
    afterEach(() => { TestBed.resetTestingModule(); vi.unstubAllGlobals(); });
    it('renders a literal title, real card, language-labelled fallback and plain escaped text', async () => {
        const fixture = TestBed.createComponent(AnkiCardsPage);
        await fixture.componentInstance.resource.ready();
        fixture.detectChanges();
        expect(fixture.nativeElement.querySelector('h2').textContent).toBe(customDeck().title);
        expect(fixture.nativeElement.querySelectorAll('.entry-card')).toHaveLength(1);
        expect(fixture.nativeElement.textContent).toContain('gato <script> "\\ (ES)');
        expect(fixture.nativeElement.querySelector('script')).toBeNull();
        expect(fixture.nativeElement.querySelector('.meta').textContent).not.toContain('frequency');
        fixture.nativeElement.querySelector('.entry-card').click();
        fixture.detectChanges();
        expect(fixture.nativeElement.querySelector('.detail').textContent).toContain('猫がいる。');
        expect(fixture.nativeElement.querySelector('app-deck-sentence-text')).toBeNull();
        fixture.destroy();
    });
    it('offers only Again/Good, persists the selected branch and permits undo', async () => {
        const first=await customCard('md-two');
        const second={...first,id:'card-dog',word:'犬',reading:'いぬ',order:2,lexicalIdentity:await lexicalIdentity({authority:'jmdict',entryId:'1251540',canonicalReading:'いぬ',homographGroup:'noun'},['犬'],'fixture'),glosses:[{...first.glosses[0],text:'perro'}]};
        await TestBed.inject(CustomDeckRepository).create('two-cards',customDeck('md-two'),[first,second]);
        Object.assign(TestBed.inject(ActivatedRoute).snapshot,{paramMap:convertToParamMap({deckId:'md-two'})});
        const fixture = TestBed.createComponent(AnkiStudyPage);
        fixture.detectChanges();
        await fixture.componentInstance.resource.ready();
        await fixture.whenStable();
        fixture.detectChanges();
        expect(fixture.componentInstance.entry()?.id).toBe('card-猫');
        expect(fixture.nativeElement.querySelector('.front').textContent).not.toContain('ねこ');
        fixture.componentInstance.reveal();
        fixture.detectChanges();
        expect(fixture.nativeElement.querySelector('.back-content').textContent).toContain('ねこ');
        expect(fixture.nativeElement.querySelectorAll('.ratings button')).toHaveLength(2);
        await fixture.componentInstance.rate('again');
        expect(await TestBed.inject(CustomDeckRepository).getDeckReviewEvents('md-two')).toHaveLength(1);
        await fixture.componentInstance.undo();
        expect(await TestBed.inject(CustomDeckRepository).getDeckReviewEvents('md-two')).toEqual([]);
        expect(fixture.componentInstance.entry()?.id).toBe('card-猫');
        fixture.destroy();
    });
    it('saves custom settings in the custom journal, not the legacy synced settings map', async () => { const fixture = TestBed.createComponent(AnkiSettingsPage); await fixture.componentInstance.resource.ready(); await fixture.whenStable(); fixture.componentInstance.setNewCards({ target: { value: '7' } } as unknown as Event); await fixture.componentInstance.save(); expect((await TestBed.inject(CustomDeckRepository).list())[0].settings.newCardsPerDay).toBe(7); expect(localStorage.getItem('kana-study.deck-settings.v1')).toBeNull(); fixture.destroy(); });
    it('computes statistics for only the custom deck', async () => {
        const fixture = TestBed.createComponent(AnkiStatsPage);
        fixture.detectChanges();
        await fixture.componentInstance.resource.ready();
        await fixture.whenStable();
        fixture.detectChanges();
        // Settle the resource effect before awaiting the statistics calculation.
        await fixture.componentInstance.ngOnInit();
        fixture.detectChanges();
        expect(fixture.componentInstance.stats()?.total).toBe(1);
        expect(fixture.componentInstance.stats()?.unseen).toBe(1);
        fixture.destroy();
    });
    it('does not grade the previous owner after a workspace switch', async () => { const fixture = TestBed.createComponent(AnkiStudyPage); fixture.detectChanges(); await fixture.componentInstance.resource.ready(); await fixture.whenStable(); fixture.componentInstance.reveal(); TestBed.inject(WorkspaceService).activateUser('other'); await fixture.componentInstance.rate('good'); expect(await TestBed.inject(CustomDeckRepository).getDeckReviewEvents('md-試験', 'guest')).toEqual([]); fixture.destroy(); });
});
