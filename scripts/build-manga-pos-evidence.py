"""Manga-only POS ambiguity evidence. Uses pinned local sources, never OCR/user data.
No handwritten surface exceptions; matches exact exported dictionary row content.
"""
import gzip
import hashlib
import json
import re
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DICTIONARY = ROOT / 'public/dictionaries/JMdict_spanish.zip'
XML = ROOT / 'experiments/manga-morphology-h2a/resources/enriched/JMdict.gz'
OUTPUT = ROOT / 'src/app/data/manga-pos-alternatives.generated.ts'
FUNCTIONAL = {'prt', 'aux', 'aux-v', 'aux-adj', 'cop', 'conj'}
LEXICAL = re.compile(r'^(n(?:-adv|-pr|-pref|-suf|-t)?|pn|adj-.+|adv(?:-to)?|int|exp|v[1245ksnr].*)$')

def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'))

def main():
    assert hashlib.sha256(DICTIONARY.read_bytes()).hexdigest() == '968c7ca9c63203315b97b0d1bdf0d021444ae9e65d8ff08c5359ba212c5abe10'
    assert hashlib.sha256(XML.read_bytes()).hexdigest() == '038a98ddefa4382fc49b98eb839506a776e7fec0c6f2c8b6cf36a711f098d63c'
    archive = zipfile.ZipFile(DICTIONARY)
    tags = [row for name in archive.namelist() if name.startswith('tag_bank_') for row in json.loads(archive.read(name))]
    codes = {row[3]: row[0] for row in tags if row[1] in ('partOfSpeech', 'expression')}
    rows = [row for name in archive.namelist() if name.startswith('term_bank_') for row in json.loads(archive.read(name))]
    wanted = {(r[0], r[1] or r[0]) for r in rows}
    alternatives = {}
    for _, entry in ET.iterparse(gzip.open(XML), events=['end']):
        if entry.tag != 'entry':
            continue
        seq = entry.findtext('ent_seq')
        spellings = [k.text for k in entry.findall('k_ele/keb')]
        for reading in entry.findall('r_ele'):
            kana = reading.findtext('reb')
            restrictions = [k.text for k in reading.findall('re_restr')]
            # A reading shared with a different written headword is not evidence
            # that the headword may be substituted into this surface.
            forms = [kana] if not spellings or reading.find('re_nokanji') is not None else restrictions or spellings
            for form in forms:
                pair = (form, kana)
                if pair not in wanted:
                    continue
                for sense in entry.findall('sense'):
                    stagk = [k.text for k in sense.findall('stagk')]
                    stagr = [k.text for k in sense.findall('stagr')]
                    if stagr and kana not in stagr or stagk and form not in stagk:
                        continue
                    # Explicit sense POS only. Never inherit the last English POS
                    # into translated senses whose tag association is absent.
                    pos = sorted({codes[p.text] for p in sense.findall('pos') if p.text in codes})
                    if pos:
                        alternatives.setdefault(pair, set()).add((seq, ' '.join(pos)))
        entry.clear()
    groups, group_ids, signatures = [], {}, {}
    for row in rows:
        options = sorted(alternatives.get((row[0], row[1] or row[0]), set()))
        families = set()
        for _, pos in options:
            words = pos.split()
            if FUNCTIONAL.intersection(words):
                families.add('functional')
            elif any(LEXICAL.fullmatch(tag) for tag in words):
                families.add('lexical')
        if len(families) < 2:
            continue
        group_key = compact(options)
        if group_key not in group_ids:
            group_ids[group_key] = len(groups)
            groups.append(options)
        # IDs of installed dictionaries are random. Match immutable row content,
        # including glosses, reading and sequence, rather than trusting an ID alone.
        signature = compact([row[0], row[1] or row[0], row[6], row[2] or '', row[3], row[5]])
        signatures[hashlib.sha256(signature.encode()).hexdigest()] = group_ids[group_key]
    provenance = {'dictionarySha256': hashlib.sha256(DICTIONARY.read_bytes()).hexdigest(),
                  'sourceArchiveSha256': hashlib.sha256(XML.read_bytes()).hexdigest(),
                  'xmlSource': 'https://www.edrdg.org/pub/Nihongo/JMdict.gz',
                  'xmlSnapshot': '2026-10-22', 'policy': 'explicit-pos-homograph-ambiguity-v1'}
    output = '// Generated by scripts/build-manga-pos-evidence.py. Manga-only, no identity equivalences.\n'
    output += 'export const MANGA_POS_PROVENANCE = ' + compact(provenance) + ';\n'
    output += 'export const MANGA_POS_GROUPS: readonly (readonly (readonly [string,string])[])[] = ' + compact(groups) + ';\n'
    output += 'export const MANGA_POS_ROWS: Readonly<Record<string,number>> = ' + compact(signatures) + ';\n'
    OUTPUT.write_text(output, encoding='utf-8')
    print(compact({'rows': len(signatures), 'groups': len(groups), 'bytes': len(output.encode()), **provenance}))

if __name__ == '__main__':
    main()
