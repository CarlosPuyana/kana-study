import { readFile, writeFile } from 'node:fs/promises';
import { parseSentenceFurigana, parseWordFurigana, sourceMarkupToPlainText } from './japanese-1500-parser.mjs';

const SOURCE_PATH = 'scripts/source/japanese-1500.normalized.json';
const DATA_PATH = 'src/app/data/japanese-1500.generated.ts';
const METADATA_PATH = 'src/app/data/japanese-1500.metadata.generated.ts';
const INDEX_PATH = 'src/app/data/japanese-1500.index.generated.ts';
const EXPECTED_COUNT = 1500;

const source = JSON.parse(await readFile(SOURCE_PATH, 'utf8'));
if (source.meta.id !== 'japanese-1500' || source.meta.contentType !== 'japanese-word') {
  throw new Error('Unexpected deck identity or content type.');
}
if (source.entries.length !== EXPECTED_COUNT || source.meta.entryCount !== EXPECTED_COUNT) {
  throw new Error(`Expected ${EXPECTED_COUNT} entries, got ${source.entries.length}.`);
}

const ids = new Set();
const guids = new Set();
const orders = new Set();
const entries = source.entries.map(entry => {
  if (ids.has(entry.id)) throw new Error(`Duplicate id: ${entry.id}`);
  if (guids.has(entry.guid)) throw new Error(`Duplicate guid: ${entry.guid}`);
  if (orders.has(entry.order)) throw new Error(`Duplicate order: ${entry.order}`);
  ids.add(entry.id);
  guids.add(entry.guid);
  orders.add(entry.order);

  for (const [field, value] of Object.entries({
    word: entry.word,
    reading: entry.reading,
    meaningEs: entry.meaning.es,
    meaningEn: entry.meaning.en,
    sentenceHtml: entry.sentenceHtml,
    sentenceFuriganaHtml: entry.sentenceFuriganaHtml,
    sentenceMeaningEs: entry.sentenceMeaning.es,
    sentenceMeaningEn: entry.sentenceMeaning.en,
  })) {
    if (!String(value ?? '').trim()) throw new Error(`Missing ${field} at order ${entry.order}.`);
  }
  if (!Number.isFinite(entry.frequencyRank)) throw new Error(`Invalid frequency at order ${entry.order}.`);

  const wordSegments = parseWordFurigana(entry.wordFurigana);
  const sentenceSegments = parseSentenceFurigana(entry.sentenceFuriganaHtml);
  const compact = value => value.replace(/\s+/g, '');
  if (compact(wordSegments.map(segment => segment.text).join('')) !== compact(entry.word)) {
    throw new Error(`Word furigana does not reconstruct order ${entry.order}.`);
  }
  if (
    compact(sentenceSegments.map(segment => segment.text).join(''))
    !== compact(sourceMarkupToPlainText(entry.sentenceFuriganaHtml.replace(/\[[^\]]+\]/g, '')))
  ) {
    throw new Error(`Sentence furigana does not reconstruct order ${entry.order}.`);
  }

  return {
    id: entry.id,
    guid: entry.guid,
    order: entry.order,
    word: entry.word,
    reading: entry.reading,
    meaning: {
      es: sourceMarkupToPlainText(entry.meaning.es),
      en: sourceMarkupToPlainText(entry.meaning.en),
    },
    wordFurigana: entry.wordFurigana,
    wordSegments,
    sentenceHtml: entry.sentenceHtml,
    sentenceFuriganaHtml: entry.sentenceFuriganaHtml,
    sentenceSegments,
    sentenceMeaning: {
      es: sourceMarkupToPlainText(entry.sentenceMeaning.es),
      en: sourceMarkupToPlainText(entry.sentenceMeaning.en),
    },
    notes: {
      es: entry.notes.es ? sourceMarkupToPlainText(entry.notes.es) : null,
      en: entry.notes.en ? sourceMarkupToPlainText(entry.notes.en) : null,
    },
    pitchAccentHtml: entry.pitchAccentHtml,
    pitchAccentNotesEn: entry.pitchAccentNotesEn,
    frequencyRank: entry.frequencyRank,
    media: { ...entry.media },
    source: entry.source,
  };
});

const expectedOrders = Array.from({ length: EXPECTED_COUNT }, (_, index) => index + 1);
if (JSON.stringify([...orders].sort((a, b) => a - b)) !== JSON.stringify(expectedOrders)) {
  throw new Error('Deck order must contain every value from 1 through 1500 exactly once.');
}
entries.sort((a, b) => a.order - b.order);

await writeFile(DATA_PATH, `/* Generated by scripts/generate-japanese-1500.mjs. Do not edit manually. */\nimport { JapaneseWordDeckEntry } from '../core/models/japanese-word-deck-entry.model';\n\nexport const JAPANESE_1500_ENTRIES: readonly JapaneseWordDeckEntry[] = ${JSON.stringify(entries, null, 2)};\n`);
await writeFile(METADATA_PATH, `/* Generated by scripts/generate-japanese-1500.mjs. Do not edit manually. */\nexport const JAPANESE_1500_METADATA = ${JSON.stringify({
  id: source.meta.id,
  nameKey: 'anki.deck.japanese1500.name',
  cardCount: source.meta.entryCount,
  contentType: source.meta.contentType,
}, null, 2)} as const;\n`);
await writeFile(INDEX_PATH, `/* Generated by scripts/generate-japanese-1500.mjs. Do not edit manually. */\nexport const JAPANESE_1500_INDEX: readonly { readonly id: string; readonly order: number }[] = ${JSON.stringify(entries.map(({ id, order }) => ({ id, order })))};\n`);

console.log(`Generated ${entries.length} Japanese deck entries.`);
