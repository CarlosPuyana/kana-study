// Reproducible, selected glyph extraction. No downloads at application runtime.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
const revision='70a0b7ae0c18ceb5cb358274b029cce0234a43bc';
const source=await readFile('src/app/data/vocabulary-n5.generated.ts','utf8');
const entries=JSON.parse(source.slice(source.indexOf('=[')+1).trim().replace(/;$/,''));
const characters=[...new Set(entries.flatMap(e=>[...e.primaryWrittenForm.normalize('NFC')]))].sort();
const kanji=characters.filter(c=>/\p{Script=Han}/u.test(c));
const directory='public/vocabulary-writing';await mkdir(directory,{recursive:true});
async function download(url){const r=await fetch(url);if(!r.ok)throw new Error(`${r.status}: ${url}`);return r.text();}
const results=[];
let next=0;
await Promise.all(Array.from({length:8},async()=>{
  while(next<kanji.length){const character=kanji[next++],code=character.codePointAt(0).toString(16).padStart(5,'0');
    const svg=await download(`https://raw.githubusercontent.com/KanjiVG/kanjivg/${revision}/kanji/${code}.svg`);
    const strokes=[...svg.matchAll(/<path\b[^>]*>/g)].flatMap(m=>{
      const id=/id="kvg:[^"]+-s(\d+)"/.exec(m[0]),d=/\bd="([^"]+)"/.exec(m[0]);
      return id&&d?[{id:id[1],value:d[1]}]:[];
    }).sort((a,b)=>Number(a.id)-Number(b.id));
    if(!strokes.length)throw new Error(`No strokes: ${character}`);
    results.push({character,viewBox:109,pathMode:'centerline',strokes,clipPaths:[]});
  }
}));
results.sort((a,b)=>a.character.codePointAt(0)-b.character.codePointAt(0));
await writeFile(`${directory}/kanji.json`,JSON.stringify(results)+'\n');
const existing=JSON.parse(await readFile('public/kana-writing/strokes.json','utf8'));
const neededKana=characters.filter(c=>!kanji.includes(c)&&!existing.some(g=>g.character===c));
const extras=[];
for(const script of ['Hiragana','Katakana']){
  const all=JSON.parse(await download(`https://cdn.jsdelivr.net/npm/kana-svg-data@0.0.2/dist/all${script}.json`));
  extras.push(...all.filter(g=>neededKana.includes(String.fromCodePoint(g.charCode))).map(g=>({character:String.fromCodePoint(g.charCode),strokes:g.strokes,clipPaths:g.clipPaths})));
}
if(neededKana.includes('ー')){
  const svg=await download('https://raw.githubusercontent.com/parsimonhi/animCJK/ec5e17cca76c87587790bcbce5ea0b4d4fb753d6/svgsJaKana/12540.svg');
  const paths=[...svg.matchAll(/<path\b[^>]*>/g)].map(m=>m[0]);
  const strokes=paths.flatMap(p=>{const id=/id="z12540d([^\"]+)"/.exec(p),d=/\bd="([^\"]+)"/.exec(p);return id&&d?[{id:id[1],value:d[1]}]:[];});
  const clipPaths=paths.flatMap(p=>{const id=/clip-path="url\(#z12540c([^\)]+)\)"/.exec(p),d=/\bd="([^\"]+)"/.exec(p);return id&&d?[{id:id[1],value:d[1]}]:[];});
  if(!strokes.length||!clipPaths.length)throw new Error('Missing long-vowel stroke');
  extras.push({character:'ー',strokes,clipPaths});
}
await writeFile(`${directory}/kana-extra.json`,JSON.stringify(extras)+'\n');
await writeFile(`${directory}/COPYING`,await download(`https://raw.githubusercontent.com/KanjiVG/kanjivg/${revision}/COPYING`));
await writeFile(`${directory}/NOTICE.txt`,`KanjiVG: copyright Ulrich Apel and contributors. CC BY-SA 3.0.\nhttps://github.com/KanjiVG/kanjivg/tree/${revision}\nhttps://creativecommons.org/licenses/by-sa/3.0/\nModification: ordered path data extracted from SVG into kanji.json; paths unchanged.\nKana extras from kana-svg-data 0.0.2 / AnimCJK, GNU LGPL v3 or later.\nhttps://github.com/hy2k/kana-svg-data\nLong vowel: AnimCJK 2016-2026 Copyright FM-SH, revision ec5e17cca76c87587790bcbce5ea0b4d4fb753d6.\nhttps://github.com/parsimonhi/animCJK\nSee ../kana-writing/NOTICE.txt and ../kana-writing/LGPL.txt.\nGenerated by scripts/generate-vocabulary-writing.mjs.\n`);
const unsupported=neededKana.filter(c=>!extras.some(g=>g.character===c));
console.log(JSON.stringify({kanji:results.length,kanaExtras:extras.length,unsupported}));

